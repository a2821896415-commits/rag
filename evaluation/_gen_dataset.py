import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
anchors = json.loads((HERE / "_golden_anchors.json").read_text(encoding="utf-8"))
# anchor_map[(item_name, content_type)] = (chunk_uid, evidence)
anchor_map = {(a[0], a[1]): (a[2], a[3]) for a in anchors}


def g(item, ctype, required=True):
    """取已校验 golden 锚点；required=False 时缺失返回 None 以便排查。"""
    if (item, ctype) not in anchor_map:
        if required:
            raise SystemExit(f"[anchor missing] {item} / {ctype}")
        return None
    uid, ev = anchor_map[(item, ctype)]
    return {
        "item_name": item,
        "content_type": ctype,
        "evidence": ev,
        "required": required,
        "chunk_uid": uid,
    }


